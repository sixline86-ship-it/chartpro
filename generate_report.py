def normalize_issue_tags(글):
    """Claude가 지정 6종 밖의 태그를 쓰면 가장 가까운 걸로 바꾸고,
    같은 태그가 3개 이상이면(=사실상 다양성 실패) 내용 키워드로 재배정한다.

    프롬프트로 "6종만 써라"라고 지시해도 가끔 어겨서, 숫자 코너와 같은 원칙으로
    코드가 마지막에 한 번 더 강제한다 — 이슈 태그도 사실 판정(분류)이라 규칙 기반이 맞다.
    """
    이슈 = 글.get("핵심이슈") or []
    for it in 이슈:
        t = (it.get("태그") or "").strip()
        if t not in ALLOWED_ISSUE_TAGS:
            텍스트 = (it.get("내용") or "") + (it.get("상세") or "")
            it["태그"] = next(
                (k for k, kws in _TAG_KEYWORDS.items() if any(w in 텍스트 for w in kws)),
                "산업")
    # 같은 태그가 절반 이상을 차지하면(다양성 실패) 두 번째부터는 재분류 시도
    from collections import Counter
    카운트 = Counter(it.get("태그") for it in 이슈)
    for 태그, n in 카운트.items():
        if n < 3:
            continue
        중복 = [it for it in 이슈 if it.get("태그") == 태그][1:]
        for it in 중복:
            텍스트 = (it.get("내용") or "") + (it.get("상세") or "")
            대안 = next(
                (k for k in ALLOWED_ISSUE_TAGS if k != 태그 and
                 any(w in 텍스트 for w in _TAG_KEYWORDS.get(k, []))),
                None)
            if 대안:
                it["태그"] = 대안
    return 글


def _too_similar(a, b):
    """두 문장이 사실상 같은지 — 어절 겹침 비율로 판단.

    프롬프트로 '다르게 쓰라'고 해도 어길 수 있어서, 코드가 마지막에 한 번 더 막는다.
    겹침 65% 이상이면 '늘려 쓴 것'으로 보고 상세를 버린다(빈 값 → 심층편은 내용으로 폴백).
    """
    import re as _re
    tok = lambda s: {w for w in _re.split(r"[^가-힣A-Za-z0-9]+", _re.sub(r"<[^>]+>", " ", s or "")) if len(w) > 1}
    A, B = tok(a), tok(b)
    if not A or not B:
        return False
    return len(A & B) / min(len(A), len(B)) >= 0.65


